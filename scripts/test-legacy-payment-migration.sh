#!/usr/bin/env bash
set -euo pipefail

: "${PGHOST:=127.0.0.1}"
: "${PGPORT:=5432}"
: "${PGUSER:=postgres}"
: "${PGPASSWORD:=postgres}"
: "${PGDATABASE:=postgres}"
export PGHOST PGPORT PGUSER PGPASSWORD PGDATABASE

psql -v ON_ERROR_STOP=1 <<'SQL'
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN BYPASSRLS;

CREATE TABLE public.customer_payment_transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid,
  amount numeric(12,2),
  status text
);

-- Deliberately model broad legacy grants, including a PUBLIC grant that must
-- not leak through to client roles after the candidate migration.
GRANT ALL PRIVILEGES ON TABLE public.customer_payment_transactions TO PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.customer_payment_transactions TO service_role;
SQL

psql -v ON_ERROR_STOP=1 -f supabase/migrations/20261015120000_lock_down_legacy_customer_payment_transactions.sql

psql -v ON_ERROR_STOP=1 <<'SQL'
DO $$
DECLARE
  client_role text;
  privilege_name text;
BEGIN
  FOREACH client_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    FOREACH privilege_name IN ARRAY ARRAY['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER'] LOOP
      IF has_table_privilege(client_role, 'public.customer_payment_transactions', privilege_name) THEN
        RAISE EXCEPTION 'Unexpected % privilege remains for %', privilege_name, client_role;
      END IF;
    END LOOP;
  END LOOP;

  IF NOT EXISTS (
    SELECT 1 FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relname = 'customer_payment_transactions'
      AND c.relrowsecurity
  ) THEN
    RAISE EXCEPTION 'RLS is not enabled on customer_payment_transactions';
  END IF;

  FOREACH privilege_name IN ARRAY ARRAY['SELECT', 'INSERT', 'UPDATE', 'DELETE'] LOOP
    IF NOT has_table_privilege('service_role', 'public.customer_payment_transactions', privilege_name) THEN
      RAISE EXCEPTION 'Expected explicit service_role % privilege was lost', privilege_name;
    END IF;
  END LOOP;

  IF NOT (SELECT rolbypassrls FROM pg_roles WHERE rolname = 'service_role') THEN
    RAISE EXCEPTION 'Test service_role fixture must bypass RLS like Supabase service_role';
  END IF;
END $$;

SELECT 'PASS: client table privileges revoked; RLS enabled; explicit service_role grants preserved' AS result;
SQL
