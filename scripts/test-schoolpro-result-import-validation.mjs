import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const page=readFileSync('src/pages/schoolpro/SchoolProResults.tsx','utf8');
const rpc=readFileSync('supabase/migrations/20261108101000_schoolpro_harden_result_import_rpc.sql','utf8');
const parse=page.slice(page.indexOf('async function parseImport'),page.indexOf('async function submitImport'));
assert.ok(parse.includes('Missing required columns'));
assert.ok(parse.includes('unsupported columns')&&parse.includes('allowedHeaders'), 'Import must reject unexpected workbook columns instead of silently ignoring them');
assert.ok(parse.includes('Assessment scheme level')&&parse.includes('student\'s class level'), 'Import preview must reject assessment schemes incompatible with the selected-session class level');
assert.ok(parse.includes('duplicate column headings'));
assert.ok(parse.includes('["junior_secondary","jss"].includes(level)')&&parse.includes('["senior_secondary","sss"].includes(level)'), "Junior and Senior Secondary scheme validation must accept canonical and short class-level aliases");
assert.ok(parse.includes('Missing component column'));
assert.ok(parse.includes('score is required and must be numeric'));
assert.ok(parse.includes('must be 0–'));
assert.ok(parse.includes('Duplicate student and subject row'));
assert.ok(parse.includes('classAssignments=')&&parse.includes('classSubjectAssignments'));
assert.ok(parse.includes('Only the subject teacher assigned to this class and subject can enter or update these scores.'));
assert.ok(parse.includes('Maximum 500 result rows'));
assert.ok(page.includes('Fix all preview errors before importing'));
assert.ok(parse.includes('Existing result is approved, published or locked'));
assert.ok(parse.includes('Existing result uses a different assessment scheme'));
assert.ok(page.includes('import_schoolpro_results'));
assert.ok(rpc.includes('Student is not enrolled in the selected session'));
assert.ok(rpc.includes('Assessment scheme level % does not match the selected class level %'));
assert.ok(rpc.includes("scheme_level='junior_secondary' and class_level in ('junior_secondary','jss')")&&rpc.includes("scheme_level='senior_secondary' and class_level in ('senior_secondary','sss')"), "Database import RPC must accept canonical and short Junior/Senior Secondary class-level aliases");
assert.ok(rpc.includes('Subject is not assigned to this class for the selected session'));
assert.ok(rpc.includes('a.ended_at is null'));
assert.ok(rpc.includes('Missing assessment component'));
assert.ok(rpc.includes('must be numeric'));
assert.ok(rpc.includes('unknown assessment component'));
assert.ok(rpc.includes('Duplicate student and subject row in import'));
assert.ok(rpc.includes('result_row.locked or result_row.status'));
assert.ok(rpc.includes('uses a different assessment scheme'));

const resultsPage = readFileSync('src/pages/schoolpro/SchoolProResults.tsx','utf8');
assert.ok(resultsPage.includes('r.assessment_scores[c.key]??"—"'), 'Saved score breakdown must show missing components as a dash, not zero');
const reportCard = readFileSync('src/pages/schoolpro/SchoolProReportCard.tsx','utf8');
assert.match(reportCard,/r\.assessment_scores\[c\.key\]\?\?['"]—['"]/, 'Report cards must not render a missing assessment component as zero');
console.log('PASS: result import requires complete headers, validates every component, rejects duplicates and preserves class/session/teacher scope.');
